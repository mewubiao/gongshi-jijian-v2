  const rejected=admin.locator(`[data-batch="${batches[1]}"]`);
  await rejected.locator('form[action="/action/reject"] input[name=reason]').fill('核实后重报演示');
  await submit(admin,rejected.getByRole('button',{name:'驳回',exact:true}));
  const revision=admin.locator(`[data-batch="${batches[1]}"] form[action="/action/revise"]`);
  await admin.locator(`[data-batch="${batches[1]}"] summary`).filter({hasText:'修正数量'}).click();
  await revision.locator('input[name=reason]').fill('确认数量无误，保留原始值与修正链');
  await submit(admin,revision.getByRole('button',{name:'记录修正并重报'}));
