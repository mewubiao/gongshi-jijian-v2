  await admin.goto(base);await snap(admin,'09-dashboard');
  // Public-terminal privacy timeout is deliberately measured in a foreground browser call.
  await worker.goto(`${base}/terminal`);await worker.waitForURL('**/login',{timeout:20000});
  check('终端15秒无操作自动退出');
  assert.equal(errors.length,0,errors.join('\n'));assert.equal(external.length,0,external.join('\n'));
  check('浏览器无脚本错误，全部页面资源本地提供，无CDN请求');
  await workerContext.close();
  await writeFile(`${out}/browser-report.json`,JSON.stringify({base,externalId,dispatchId,checks,errors,external,at:new Date().toISOString()},null,2));
